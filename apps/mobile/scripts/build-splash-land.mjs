#!/usr/bin/env node
/**
 * Rasterises the continents the opening's globe wears.
 *
 *   node apps/mobile/scripts/build-splash-land.mjs
 *
 * Source: Natural Earth 1:110m land, v5.1.2 — public domain, so no credit line
 * is owed anywhere. At 110m the coastlines are coarse, which is right for a
 * sphere 192 points across.
 *
 * Output: `lib/splash/land.generated.ts`, a 1024 × 512 equirectangular mask
 * (longitude −180 at the left, north at the top), run-length encoded. It is
 * committed and regenerated only by hand, because the land does not change.
 *
 * Why a mask in a TypeScript module and not a PNG: the opening draws with
 * `three` over `expo-gl`, and there is no browser canvas on the phone to draw an
 * outline into, nor a loader that turns a PNG asset into a texture without
 * another dependency. A typed array is the one thing `three` can upload as it
 * is. The encoding is runs of alternating sea and land, row by row, written in
 * base 36 and separated by commas: about 14 KB, expanded once at launch.
 */

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson'
const WIDTH = 1024
const HEIGHT = 512
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'splash', 'land.generated.ts')

const response = await fetch(SOURCE)
if (!response.ok) throw new Error(`Could not fetch ${SOURCE}: ${response.status}`)
const land = await response.json()

/** Every ring as pixel coordinates. Holes are rings too; even-odd filling handles them. */
const rings = []
for (const feature of land.features) {
  const { type, coordinates } = feature.geometry
  const polygons = type === 'Polygon' ? [coordinates] : coordinates
  for (const polygon of polygons) {
    for (const ring of polygon) {
      rings.push(ring.map(([lon, lat]) => [((lon + 180) / 360) * WIDTH, ((90 - lat) / 180) * HEIGHT]))
    }
  }
}

const mask = new Uint8Array(WIDTH * HEIGHT)
for (let row = 0; row < HEIGHT; row++) {
  const y = row + 0.5
  const crossings = []
  for (const ring of rings) {
    for (let i = 0; i < ring.length - 1; i++) {
      const [x1, y1] = ring[i]
      const [x2, y2] = ring[i + 1]
      if ((y1 <= y && y2 > y) || (y2 <= y && y1 > y)) {
        crossings.push(x1 + ((y - y1) / (y2 - y1)) * (x2 - x1))
      }
    }
  }
  crossings.sort((a, b) => a - b)
  for (let k = 0; k + 1 < crossings.length; k += 2) {
    const from = Math.max(0, Math.round(crossings[k]))
    const to = Math.min(WIDTH, Math.round(crossings[k + 1]))
    mask.fill(1, row * WIDTH + from, row * WIDTH + to)
  }
}

const runs = []
let current = 0
let length = 0
for (const value of mask) {
  if (value === current) {
    length++
  } else {
    runs.push(length)
    current = value
    length = 1
  }
}
runs.push(length)

writeFileSync(
  OUT,
  `/**
 * GENERATED by apps/mobile/scripts/build-splash-land.mjs — do not edit.
 *
 * Natural Earth 1:110m land (public domain) as a ${WIDTH} × ${HEIGHT} equirectangular
 * mask: runs of alternating sea and land, starting with sea, row by row from the
 * north, in base 36. \`land.ts\` expands it.
 */
export const LAND_WIDTH = ${WIDTH}
export const LAND_HEIGHT = ${HEIGHT}
export const LAND_RUNS =
  '${runs.map((n) => n.toString(36)).join(',')}'
`,
)
console.log(`Wrote ${runs.length} runs to ${OUT}`)
